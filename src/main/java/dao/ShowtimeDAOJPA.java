package dao;

import jakarta.persistence.*;
import java.util.List;
import model.Showtime;

/**
 * JPA implementation of {@link ShowtimeDAO}.
 * <p>
 * Uses an {@link EntityManager} to read and write {@link Showtime} entities in
 * the {@code showtimes} table. Every operation that modifies data runs inside
 * a transaction: if something fails, the transaction is rolled back and the
 * error is wrapped in a {@link DAOException}, so the upper layers never deal
 * with JPA exceptions directly.
 *
 * @author Matias Rosas
 * @author Camila Larsen
 * @author Matias Nerli
 * @version 1.0
 */
public class ShowtimeDAOJPA implements ShowtimeDAO {

    /**
     * The entity manager used for all the database operations.
     */
    private final EntityManager em;

    /**
     * Creates a new DAO that works with the given entity manager.
     *
     * @param em the entity manager to use; it is shared with the other DAOs
     *           of the application
     */
    public ShowtimeDAOJPA(EntityManager em) {
        this.em = em;
    }

    /**
     * Saves a new showtime in the database.
     * <p>
     * After this method returns, the showtime has the ID generated by the
     * database.
     *
     * @param s the showtime to save; its ID must be {@code null}
     * @throws DAOException if the showtime could not be saved
     */
    @Override
    public void insert(Showtime s) throws DAOException {
        EntityTransaction tx = em.getTransaction();
        try {
            tx.begin();
            em.persist(s);
            tx.commit();
        } catch (PersistenceException e) {
            if (tx.isActive()) {
                tx.rollback();
            }
            throw new DAOException("No se pudo agregar la funcion.", e);
        }
    }

    /**
     * Finds a showtime by its ID.
     *
     * @param id the ID of the showtime to find
     * @return the showtime, or {@code null} if no showtime has that ID
     * @throws DAOException if the search could not be performed
     */
    @Override
    public Showtime findById(Long id) throws DAOException {
        try {
            return em.find(Showtime.class, id);
        } catch (PersistenceException e) {
            throw new DAOException("No se pudo buscar la funcion con id " + id, e);
        }
    }

    /**
     * Returns all the showtimes, ordered by date and then by start time.
     *
     * @return the list of showtimes; empty if there are none
     * @throws DAOException if the showtimes could not be read
     */
    @Override
    public List<Showtime> findAll() throws DAOException {
        try {
            return em.createQuery(
                    "SELECT s FROM Showtime s ORDER BY s.date, s.startTime", Showtime.class)
                    .getResultList();
        } catch (PersistenceException e) {
            throw new DAOException("No se pueden mostrar las funciones.", e);
        }
    }

    /**
     * Counts how many showtimes belong to a movie.
     * <p>
     * Used to prevent deleting a movie that still has showtimes scheduled.
     *
     * @param movieId the ID of the movie
     * @return the number of showtimes of that movie; {@code 0} if it has none
     * @throws DAOException if the count could not be performed
     */
    @Override
    public long countByMovie(Long movieId) throws DAOException {
        try {
            return em.createQuery(
                    "SELECT COUNT(s) FROM Showtime s WHERE s.movie.id = :movieId", Long.class)
                    .setParameter("movieId", movieId)
                    .getSingleResult();
        } catch (PersistenceException e) {
            throw new DAOException("No se pudieron contar las funciones de la pelicula.", e);
        }
    }

    /**
     * Updates an existing showtime with the data of the given object.
     * <p>
     * The showtime is identified by its ID, which must already exist in the
     * database.
     *
     * @param s the showtime with the new data; its ID must not be {@code null}
     * @throws DAOException if the showtime could not be updated
     */
    @Override
    public void update(Showtime s) throws DAOException {
        EntityTransaction tx = em.getTransaction();
        try {
            tx.begin();
            em.merge(s);
            tx.commit();
        } catch (PersistenceException e) {
            if (tx.isActive()) {
                tx.rollback();
            }
            throw new DAOException("No se pudo actualizar la funcion.", e);
        }
    }

    /**
     * Deletes the showtime with the given ID.
     * <p>
     * If no showtime has that ID, nothing happens.
     *
     * @param id the ID of the showtime to delete
     * @throws DAOException if the showtime could not be deleted
     */
    @Override
    public void delete(Long id) throws DAOException {
        EntityTransaction tx = em.getTransaction();
        try {
            tx.begin();
            Showtime s = em.find(Showtime.class, id);
            if (s != null) {
                em.remove(s);
            }
            tx.commit();
        } catch (PersistenceException e) {
            if (tx.isActive()) {
                tx.rollback();
            }
            throw new DAOException("No se pudo eliminar la funcion.", e);
        }
    }
}
